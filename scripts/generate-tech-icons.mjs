// Generates src/content/tech-icons.generated.ts from the CC0 `simple-icons`
// package so tech logos are bundled locally (no CDN hot-linking).
// Run: node scripts/generate-tech-icons.mjs
import { writeFile } from "node:fs/promises";
import * as icons from "simple-icons";

const wanted = {
  react: "siReact",
  nextjs: "siNextdotjs",
  vue: "siVuedotjs",
  javascript: "siJavascript",
  typescript: "siTypescript",
  tailwind: "siTailwindcss",
  nestjs: "siNestjs",
  java: "siOpenjdk",
  nodejs: "siNodedotjs",
  mongodb: "siMongodb",
  postgresql: "siPostgresql",
  mysql: "siMysql",
};

const entries = Object.entries(wanted).map(([key, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`Missing icon ${exportName}`);
  return `  ${key}: { path: ${JSON.stringify(icon.path)}, hex: "#${icon.hex}" },`;
});

const socials = { facebook: "siFacebook", instagram: "siInstagram" };
const socialEntries = Object.entries(socials).map(([key, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`Missing icon ${exportName}`);
  return `  ${key}: ${JSON.stringify(icon.path)},`;
});

const out = `// AUTO-GENERATED by scripts/generate-tech-icons.mjs — do not edit by hand.
// Icon paths from simple-icons (CC0-1.0). Brand names are trademarks of their owners.
export const techIcons = {
${entries.join("\n")}
} as const;

export type TechIconKey = keyof typeof techIcons;

export const socialIcons = {
${socialEntries.join("\n")}
  // LinkedIn is not distributed by simple-icons; simplified "in" glyph.
  linkedin: "M20.45 20.45h-3.56v-5.57c0-1.33-.02-3.04-1.85-3.04-1.86 0-2.14 1.45-2.14 2.94v5.67H9.35V9h3.41v1.56h.05c.48-.9 1.64-1.85 3.37-1.85 3.6 0 4.27 2.37 4.27 5.46v6.28ZM5.34 7.43a2.06 2.06 0 1 1 0-4.13 2.06 2.06 0 0 1 0 4.13ZM7.12 20.45H3.56V9h3.56v11.45ZM22.22 0H1.77C.79 0 0 .77 0 1.73v20.54C0 23.23.79 24 1.77 24h20.45c.98 0 1.78-.77 1.78-1.73V1.73C24 .77 23.2 0 22.22 0Z",
} as const;
`;

await writeFile("src/content/tech-icons.generated.ts", out);
console.log(`Wrote ${entries.length} icons`);
